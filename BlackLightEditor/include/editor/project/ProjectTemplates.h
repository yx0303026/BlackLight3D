#pragma once

#include "editor/project/ProjectFile.h"
#include "editor/project/TemplateEngine.h"

#include <string>
#include <string_view>
#include <vector>

namespace BlackLight::Editor
{

	/// Owns the built-in, versioned project templates.
	class TemplateLibrary final
	{
	public:
		/// Builds the templates embedded in the editor executable.
		TemplateLibrary();

		/// Returns the template for a project kind, or null when it is unavailable.
		const ProjectTemplate *Find(ProjectKind kind) const noexcept;
		/// Returns every template in project-kind order.
		const std::vector<ProjectTemplate> &GetTemplates() const noexcept;
		/// Returns the template version for a project kind, or an empty string.
		std::string GetVersion(ProjectKind kind) const;

		/// Returns the BlackLight engine version expected by the templates.
		static std::string GetEngineVersion();
		/// Returns whether a project was generated by an older template version.
		bool IsUpdateAvailable(const ProjectMetadata &metadata) const;

	private:
		std::vector<ProjectTemplate> templates_;
	};

} // namespace BlackLight::Editor
