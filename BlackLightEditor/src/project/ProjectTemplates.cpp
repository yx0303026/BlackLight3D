	TemplateLibrary::TemplateLibrary()
	{
		ProjectTemplate windows_app;
		windows_app.kind = ProjectKind::WindowsApp;
		windows_app.version = TemplateVersion;
		windows_app.description = "Desktop application with a selectable graphics API";
		windows_app.directories = {"src", "include", "assets", "ui", "cmake", "build"};
		windows_app.files = {
			File("CMakeLists.txt", ApplicationCMakeLists(), TemplateFilePolicy::Regenerate),
			File("CMakePresets.json", CommonPresets(), TemplateFilePolicy::Regenerate),
			File(".gitignore", CommonGitIgnore()),
			File("app.manifest", CommonManifest()),
			File("README.md", WindowsAppReadme()),
			File("src/main.cpp", WindowsAppMain()),
			File("assets/.gitkeep", {}),
			File("ui/.gitkeep", {}),
		};

		ProjectTemplate game;
		game.kind = ProjectKind::BlackLightGame;
		game.version = TemplateVersion;
		game.description = "Game project with the engine game loop and content root";
		game.directories = {"src", "include", "assets", "ui", "cmake", "build"};
		game.files = {
			File("CMakeLists.txt", ApplicationCMakeLists(), TemplateFilePolicy::Regenerate),
			File("CMakePresets.json", CommonPresets(), TemplateFilePolicy::Regenerate),
			File(".gitignore", CommonGitIgnore()),
			File("app.manifest", CommonManifest()),
			File("README.md", GameReadme()),
			File("src/main.cpp", GameMain()),
			File("assets/.gitkeep", {}),
			File("ui/.gitkeep", {}),
		};

		ProjectTemplate inject;
		inject.kind = ProjectKind::BlockLightUIInject;
		inject.version = TemplateVersion;
		inject.description = "DLL shell with an exported plugin API for UI injection";
		inject.directories = {"src", "include", "assets", "cmake", "build"};
		inject.files = {
			File("CMakeLists.txt", InjectCMakeLists(), TemplateFilePolicy::Regenerate),
			File("CMakePresets.json", CommonPresets(), TemplateFilePolicy::Regenerate),
			File(".gitignore", CommonGitIgnore()),
			File("README.md", InjectReadme()),
			File("include/PluginApi.h", InjectApiHeader()),
			File("src/dllmain.cpp", InjectDllMain()),
			File("src/plugin.cpp", InjectPluginSource()),
			File("src/${PROJECT_TARGET}.def", InjectDefFile()),
			File("assets/.gitkeep", {}),
		};

		templates_ = {std::move(windows_app), std::move(game), std::move(inject)};
	}

	const ProjectTemplate *TemplateLibrary::Find(ProjectKind kind) const noexcept
	{
		const auto it = std::find_if(templates_.begin(), templates_.end(),
			[kind](const ProjectTemplate &project_template)
			{
				return project_template.kind == kind;
			});
		return it == templates_.end() ? nullptr : &*it;
	}

	const std::vector<ProjectTemplate> &TemplateLibrary::GetTemplates() const noexcept
	{
		return templates_;
	}

	std::string TemplateLibrary::GetVersion(ProjectKind kind) const
	{
		const ProjectTemplate *project_template = Find(kind);
		return project_template ? project_template->version : std::string();
	}

	std::string TemplateLibrary::GetEngineVersion() { return EngineVersion; }

	bool TemplateLibrary::IsUpdateAvailable(const ProjectMetadata &metadata) const
	{
		const ProjectTemplate *project_template = Find(metadata.kind);
		if (!project_template)
			return false;
		return metadata.template_version != project_template->version;
	}

